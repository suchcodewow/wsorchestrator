/**
 * Dress the callouts that `remarkBlockDirectives` built.
 *
 * Here rather than in that plugin for the same reason `<details>` is dressed
 * here: a class on a `div` is not in the sanitiser's schema, so anything set
 * before it runs is stripped straight back off. The one thing that *does* come
 * through is `data-callout`, which is what this pass reads the kind from — and
 * the kind was chosen from a closed set on the way in, so what arrives here is
 * one of five words rather than anything an author typed.
 *
 * The heading is the box's first paragraph, always present by construction. The
 * body is wrapped so it can be spaced as a document of its own: `.lab-prose`'s
 * rhythm rule only reaches its own direct children, and a callout two paragraphs
 * long would otherwise set solid.
 */
function rehypeCallouts() {
  return (tree: Root) => {
    visit(tree, "element", (node: Element) => {
      if (node.tagName !== "div") return;

      const kind = node.properties["data-callout"];
      if (typeof kind !== "string" || !(kind in CALLOUTS)) return;

      const head = node.children.find((c): c is Element => isElement(c, "p"));
      if (!head) return;

      addClass(node, "lab-callout");
      addClass(head, "lab-callout-head");
      head.children = [
        calloutIcon(kind as CalloutKind),
        el("span", { className: ["lab-callout-title"] }, head.children),
      ];

      const body = node.children.filter((c) => c !== head);
      node.children = [
        head,
        // A callout can be a heading and nothing else — a one-line aside whose
        // title says all of it — and a wrapper there would pad out a void.
        ...(body.some((c) => c.type !== "text" || c.value.trim().length > 0)
          ? [el("div", { className: ["lab-callout-body"] }, body)]
          : []),
      ];
    });
  };
}

/* ------------------------------------------------------------------ *
 * Headings and links
 * ------------------------------------------------------------------ */

/**
 * Give every h2/h3 a stable id and collect them for the page's contents list.
 *
 * The slugger is created per document rather than per plugin instance: it
 * remembers what it has already issued so a guide with two "Verify" sections
 * gets `verify` and `verify-1`, and a shared one would carry that state across
 * unrelated guides.
 */
function rehypeHeadings() {
  return (tree: Root, file: { data: Record<string, unknown> }) => {
    const slugger = new GithubSlugger();
    const toc: TocEntry[] = [];

    visit(tree, "element", (node: Element) => {
      if (node.tagName !== "h2" && node.tagName !== "h3") return;

      const text = toString(node);
      const id =
        typeof node.properties.id === "string" && node.properties.id.length > 0
          ? node.properties.id
          : slugger.slug(text || "section");

      node.properties.id = id;
      // The whole heading is the anchor, so the target is as big as the words
      // rather than a link icon that has to be hunted for on hover.
      node.children = [
        el("a", { href: `#${id}`, className: ["heading-anchor"] }, node.children),
      ];

      toc.push({ id, text, depth: node.tagName === "h2" ? 2 : 3 });
    });

    file.data.toc = toc;
  };
}

/**
 * Send off-site links to a new tab. `noopener` is the point — `noreferrer` for
 * the same reason it always is — since a guide is a public page and the link
 * target is whatever a manager typed.
 */
function rehypeExternalLinks() {
  return (tree: Root) => {
    visit(tree, "element", (node: Element) => {
      if (node.tagName !== "a") return;
      const href = node.properties.href;
      if (typeof href !== "string" || !/^https?:\/\//i.test(href)) return;

      node.properties.target = "_blank";
      node.properties.rel = ["noopener", "noreferrer"];
    });
  };
}

/* ------------------------------------------------------------------ *
 * Source positions
 * ------------------------------------------------------------------ */

/**
 * The blocks worth pointing back at their source line.
 *
 * Block-level only: an anchor or a run of bold text starts somewhere in the
 * middle of a line, and a mapping that fine buys nothing — the finest thing
 * anyone can scroll to is the paragraph it sits in. `li` and `tr` are in the
 * list on purpose, since a long list or table is otherwise a single landmark
 * covering a screenful of source.
 */
const LINE_MARKED_TAGS = new Set([
  "p",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "ul",
  "ol",
  "li",
  "blockquote",
  "pre",
  "figure",
  // A collapsible section marks both: the summary is what is on screen while
  // it is shut, and the section itself is the landmark once it is open.
  "details",
  "summary",
  // The only `div` with a position of its own is a callout: nothing else in the
  // pipeline emits one from the source, and the wrappers built afterwards have
  // no position to mark.
  "div",
  "table",
  "thead",
  "tbody",
  "tr",
  "hr",
  "dl",
  "dt",
  "dd",
]);

/**
 * Record the source line each block came from, as `data-line`.
 *
 * Only the editor's preview asks for this: it is what lets the split view
 * scroll the rendered side to the part of the guide being typed. A published
 * page has no markdown to line up against, so it renders without the
 * attributes rather than carrying a few hundred of them for nobody.
 *
 * Runs last, after the code blocks have been rebuilt — a fence's `figure` is
 * generated markup that carries the fence's position forward by hand, and
 * everything Shiki puts inside it has no position at all, so the block gets one
 * mark on the outside instead of one per highlighted line.
 */
function rehypeSourceLines() {
  return (tree: Root) => {
    visit(tree, "element", (node: Element) => {
      const line = node.position?.start.line;
      if (line === undefined || !LINE_MARKED_TAGS.has(node.tagName)) return;
      node.properties["data-line"] = String(line);
    });
  };
}

/* ------------------------------------------------------------------ *
 * The pipeline
 * ------------------------------------------------------------------ */

/**
 * GitHub's rules, plus the one attribute this renderer needs to survive them.
 *
 * `data-callout` is how a callout's kind reaches the far side of the sanitiser,
 * where the box is dressed (`rehypeCallouts`). A class would not get there —
 * `div` has none in the schema — and the trick the fence titles use, folding the
 * value into a `language-*` class, has no equivalent on a `div`.
 *
 * Widening the schema is safe here in a way it would not usually be: the only
 * `div` in the tree at this point is one `remarkBlockDirectives` built, since raw
 * HTML never survives the parse, and the value is one of five words that plugin
 * chose from a closed set. The list is spelled out anyway, so an attribute that
 * somehow arrives holding anything else is dropped rather than trusted.
 */
const SANITIZE_SCHEMA = {
  ...defaultSchema,
  attributes: {
    ...defaultSchema.attributes,
    div: [
      ...(defaultSchema.attributes?.div ?? []),
      ["data-callout", ...Object.keys(CALLOUTS)] as [string, ...string[]],
    ],
  },
};

const buildProcessor = (highlighter: Highlighter, sourceLines: boolean) => {
  const processor = unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkDirective)
    .use(remarkBlockDirectives)
    .use(remarkRehype)
    .use(rehypeCarryCodeTitle)
    // GitHub's default rules, which already keep `language-*` on a code
    // element — `language-hcl:main.tf` included, which is what lets the fence
    // title survive this step — and which allow `details` and `summary`, which
    // is what lets a collapsible section through with its contents sanitised.
    .use(rehypeSanitize, SANITIZE_SCHEMA)
    // Everything below this line generates trusted markup.
    .use(rehypeHighlight, highlighter)
    .use(rehypeDetails)
    .use(rehypeCallouts)
    .use(rehypeHeadings)
    .use(rehypeExternalLinks);

  if (sourceLines) processor.use(rehypeSourceLines);

  return processor.use(rehypeStringify);
};

/**
 * The pipelines, built once each. Plugins hold no per-document state — the one
 * that would, the heading slugger, creates its own inside the transform — so a
 * single processor is safe to share across concurrent requests.
 *
 * Two of them, keyed by whether the output carries source lines: the flag
 * changes the plugin list, and the only alternative is rebuilding the pipeline
 * (and with it the reference to the highlighter) per request.
 */
const processors = new Map<
  boolean,
  Promise<ReturnType<typeof buildProcessor>>
>();

function getProcessor(sourceLines: boolean) {
  let processor = processors.get(sourceLines);
  if (!processor) {
    processor = getHighlighter().then((h) => buildProcessor(h, sourceLines));
    processors.set(sourceLines, processor);
  }
  return processor;
}

/** Render a guide body to HTML, with the headings it turned out to have. */
export async function renderMarkdown(
  markdown: string,
  {
    /**
     * Mark each block with the source line it came from, for an editor that
     * wants to line the rendering up against the markdown it was typed from.
     */
    sourceLines = false,
  }: { sourceLines?: boolean } = {},
): Promise<RenderedMarkdown> {
  if (markdown.trim().length === 0) return { html: "", toc: [] };

  const processor = await getProcessor(sourceLines);
  // Both passes run before anything parses the text, so `remarkBlockDirectives`
  // — which reads offsets back out of the source it was given — and `data-line`
  // describe the same string. Neither adds or removes a line, so the numbers
  // still point at the markdown the author is looking at.
  const file = await processor.process(
    normaliseListIndents(normaliseDirectiveTitles(markdown)),
  );

  return {
    html: String(file),
    toc: (file.data as { toc?: TocEntry[] }).toc ?? [],
  };
}
