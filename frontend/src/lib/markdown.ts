/**
 * Markdown → HTML for lab guides.
 *
 * All of this runs on the server and ships zero markdown code to the browser:
 * a guide is read far more often than it is written, and the reader should not
 * pay to parse a document that was already parsed. The one client-side piece is
 * the copy buttons (`@/components/lab-guide-body`), which attach to markup
 * generated here.
 *
 * Two rules the pipeline order encodes:
 *
 *  1. Raw HTML in the source is dropped, not rendered — `remark-rehype` ignores
 *     it unless `allowDangerousHtml` is set, and it is not set. Authors write
 *     Markdown; they do not get an HTML injection point into a public page.
 *  2. `rehype-sanitize` runs on the author's tree and nothing else. Everything
 *     added afterwards — heading ids, link rels, the entire highlighted code
 *     block — is generated by this file, so sanitising it again would only
 *     strip our own attributes back off.
 */

