/* ------------------------------------------------------------------ *
 * Code fence info strings
 * ------------------------------------------------------------------ */

/**
 * Carry a fence's title through sanitisation.
 *
 * ```` ```bash title="setup.sh" ```` puts "setup.sh" in the mdast node's meta,
 * which `rehype-sanitize` drops — it rebuilds every node from the attributes
 * its schema allows, and `data` is not an attribute. The class name *does*
 * survive (the default schema keeps `language-*` on `code`), so the title is
 * folded into it here and unpacked again on the other side.
 *
 * Encoded because a class attribute cannot contain spaces, and "Step 2 — main.tf"
 * is exactly the sort of title somebody will write.
 */
function rehypeCarryCodeTitle() {
  return (tree: Root) => {
    visit(tree, "element", (node: Element) => {
      if (node.tagName !== "code") return;

      const meta = (node.data as { meta?: string } | undefined)?.meta;
      if (!meta) return;

      const title = meta.match(/(?:^|\s)title=(?:"([^"]*)"|'([^']*)'|(\S+))/);
      const value = title?.[1] ?? title?.[2] ?? title?.[3];
      if (!value) return;

      const classes = Array.isArray(node.properties.className)
        ? node.properties.className
        : [];
      const lang = classes.find(
        (c) => typeof c === "string" && c.startsWith("language-"),
      );
      if (typeof lang !== "string") return;

      node.properties.className = classes.map((c) =>
        c === lang ? `${lang}:${encodeURIComponent(value)}` : c,
      );
    });
  };
}

/** The language and optional title a fence asked for. */
function parseInfo(code: Element): { lang: string; title: string | null } {
  const classes = Array.isArray(code.properties.className)
    ? code.properties.className
    : [];
  const marker = classes.find(
    (c): c is string => typeof c === "string" && c.startsWith("language-"),
  );
  if (!marker) return { lang: "text", title: null };

  const [lang, encoded] = marker.slice("language-".length).split(":", 2);
  let title: string | null = null;
  if (encoded) {
    try {
      title = decodeURIComponent(encoded);
    } catch {
      // A title that survived this far but won't decode isn't worth a 500.
      title = encoded;
    }
  }
  return { lang: lang.toLowerCase() || "text", title };
}

/* ------------------------------------------------------------------ *
 * List indentation
 * ------------------------------------------------------------------ */

/** A line that opens a list item: its indent, its marker, the gap after it. */
const LIST_ITEM = /^([ \t]*)([-*+]|\d{1,9}[.)])([ \t]+)(?=\S)/;

/** A fence, once the line's indent (and any list marker) is off the front. */
const FENCE = /^(`{3,}|~{3,})(.*)$/;

/** How far past a marker's own indent a line has to be to be inside the item. */
const CONTINUATION = 2;

/** Leading whitespace as a column, counting a tab to the next stop of four. */
function indentWidth(line: string): number {
  let width = 0;
  for (const ch of line) {
    if (ch === " ") width += 1;
    else if (ch === "\t") width += 4 - (width % 4);
    else break;
  }
  return width;
}

/** Move a line right, leaving blank lines blank. */
const shiftLine = (line: string, by: number): string =>
  by > 0 && line.trim().length > 0 ? " ".repeat(by) + line : line;

/**
 * Re-indent under-indented blocks so they stay in the list item they follow.
 *
 * Markdown keeps a block inside a list item only while it is indented to that
 * item's *content column* — three for `1. `, four for `10. `, two for `- `. A
 * fence or an image one space short of that closes the list instead, and the
 * steps below it become a second list numbered from one. Nothing about the
 * source shows it: two spaces looks indented, and the rule that two is enough
 * under a bullet but not under a number is not one anybody should have to hold
 * in their head while writing a lab.
 *
 * So the guides get one rule — two spaces means "still inside this step" — and
 * this pass turns that into whatever column the parser actually wants, before
 * the parser sees it. Indenting is all it does: a line is only ever moved
 * right, and only ever to the content column of the item it is already inside,
 * so a correctly indented guide passes through untouched.
 *
 * Line-for-line, deliberately. The editor's preview lines its scroll up against
 * `data-line`, and every one of those numbers comes from parsing what this
 * function returns — so it may change what a line starts with, but never how
 * many there are.
 *
 * Fenced code is copied through with the shift its opening fence got and
 * nothing else: a list marker is only a list marker in prose, and these guides
 * are full of YAML, whose every sequence entry would otherwise open an item and
 * drag the rest of the block in after it.
 */
function normaliseListIndents(markdown: string): string {
  const lines = markdown.split("\n");
  const out: string[] = [];

  /** The list items currently open, outermost first. */
  const open: { srcIndent: number; contentColumn: number }[] = [];
  /** The fence being copied through, if the walk is inside one. */
  let fence: { marker: string; by: number; floor: number } | null = null;

  for (const line of lines) {
    if (fence) {
      // Code keeps its shape relative to its fence, but no line may sit left
      // of the item's content column: a fence moved into a step takes its
      // contents with it, and a line short of that column would end the step —
      // closing the block early and spilling the rest of the code into the
      // page as prose.
      out.push(
        shiftLine(line, Math.max(fence.by, fence.floor - indentWidth(line))),
      );

      // A closing fence is the same character, at least as long, and alone on
      // its line — anything else is code that happens to start with backticks.
      const close = line.trim().match(FENCE);
      if (
        close &&
        close[1][0] === fence.marker[0] &&
        close[1].length >= fence.marker.length &&
        close[2].trim().length === 0
      ) {
        fence = null;
      }
      continue;
    }

    // A blank line separates blocks but does not end a list, so it neither
    // closes an item nor needs moving.
    if (line.trim().length === 0) {
      out.push(line);
      continue;
    }

    const width = indentWidth(line);

    // Anything not far enough in has left the items it is not far enough for.
    while (
      open.length > 0 &&
      width < open[open.length - 1].srcIndent + CONTINUATION
    ) {
      open.pop();
    }

    const item = open[open.length - 1];
    const by = item ? Math.max(0, item.contentColumn - width) : 0;
    out.push(shiftLine(line, by));

    const opened = line.match(LIST_ITEM);
    if (opened) {
      // Where this item's own content starts, in the output.
      const marker = opened[2].length + opened[3].length;
      open.push({ srcIndent: width, contentColumn: width + by + marker });
    }

    // A fence opens on its own line, or directly after a marker on the line
    // that opened the item.
    const rest = opened ? line.slice(opened[0].length) : line.trimStart();
    const start = rest.match(FENCE);
    if (start) {
      // A fence on a marker line belongs to the item that marker just opened.
      const inner = opened ? open[open.length - 1] : item;
      fence = { marker: start[1], by, floor: inner?.contentColumn ?? 0 };
    }
  }

  return out.join("\n");
}

/* ------------------------------------------------------------------ *
 * Callouts
 * ------------------------------------------------------------------ */

/**
 * The kinds of callout a guide can write, and the heading each falls back to
 * when it is opened without one.
 *
 * Five, deliberately. A palette of callouts only means anything while a reader
 * can tell them apart at a glance, and a guide with eight shades of tinted box
 * in it has none — every one of these has its own hue *and* its own glyph.
 *
 * `note` is the quiet one, in the palette's own slate: an aside that is worth
 * setting apart from the prose but is not a hazard. The other four are coloured
 * by what they cost the reader if ignored, which is why `danger` borrows
 * `--destructive` rather than introducing a second red.
 */
const CALLOUTS = {
  note: "Note",
  tip: "Tip",
  success: "Success",
  warning: "Warning",
  danger: "Caution",
} as const;

type CalloutKind = keyof typeof CALLOUTS;

/**
 * Other names for the same box.
 *
 * GitHub's alert syntax and Docusaurus's admonitions between them have taught
 * everybody a slightly different vocabulary, and a guide that says `:::caution`
 * meant a callout — not a paragraph beginning with three colons. Mapped rather
 * than added as kinds of their own so the rendering stays the five above.
 */
const CALLOUT_ALIASES: Record<string, CalloutKind> = {
  info: "note",
  important: "note",
  caution: "danger",
  error: "danger",
  warn: "warning",
  check: "success",
};

/** The callout kind a directive name asks for, if it asks for one. */
const calloutKind = (name: string): CalloutKind | null =>
  name in CALLOUTS
    ? (name as CalloutKind)
    : (CALLOUT_ALIASES[name] ?? null);

/* ------------------------------------------------------------------ *
 * Directive titles
 * ------------------------------------------------------------------ */

/** A block directive that takes a title: the callouts, plus `details`. */
const hasTitle = (name: string): boolean =>
  name === "details" || calloutKind(name) !== null;

/**
 * A directive opening with something other than a label after its name:
 * the indent, the name, and the rest of the line.
 */
const DIRECTIVE_OPEN = /^([ \t]*):{3,}([A-Za-z][A-Za-z\d-]*)[ \t]+(\S.*?)[ \t]*$/;

/**
 * Let a callout's title be written as plain text after its name.
 *
 * `remark-directive`'s own spelling puts the title in brackets —
 * `:::tip[Stop and smell the code]` — and a container directive whose opening
 * line has anything *else* on it is not a directive at all: the extension
 * declines it, and the whole block, closing `:::` included, lands in the page as
 * a paragraph of literal punctuation. That is a silent failure of exactly the
 * kind an author cannot debug, over a pair of brackets that carry no meaning of
 * their own.
 *
 * So both spellings are accepted, and this pass turns the loose one into the
 * strict one before anything parses it. Line-for-line, like
 * `normaliseListIndents` — `data-line` and the editor's preview scrolling both
 * depend on the line numbers surviving every pass.
 *
 * Only the names this renderer knows are rewritten. An unrecognised directive is
 * put back into the page as the text that was typed (see
 * `remarkBlockDirectives`), and it should read as what the author wrote rather
 * than as something this pass did to it on the way past.
 */
function normaliseDirectiveTitles(markdown: string): string {
  let fence: string | null = null;

  return markdown
    .split("\n")
    .map((line) => {
      // Three colons in a shell heredoc or a YAML block are not a directive.
      const marker = line.trim().match(FENCE);
      if (fence) {
        if (
          marker &&
          marker[1][0] === fence[0] &&
          marker[1].length >= fence.length &&
          marker[2].trim().length === 0
        ) {
          fence = null;
        }
        return line;
      }
      if (marker) {
        fence = marker[1];
        return line;
      }

      const open = line.match(DIRECTIVE_OPEN);
      if (!open || !hasTitle(open[2].toLowerCase())) return line;

      // Already in the strict form, give or take a space — `:::tip [a]` or
      // `:::details[x] {open}`. Nothing to do, and guessing would break it.
      const rest = open[3];
      if (rest.startsWith("[") || rest.startsWith("{")) return line;

      // The title becomes the contents of a bracketed label, so its own
      // brackets have to stop being label syntax.
      const label = rest.replace(/[[\]\\]/g, "\\$&");
      return `${open[1]}:::${open[2]}[${label}]`;
    })
    .join("\n");
}

/* ------------------------------------------------------------------ *
 * Collapsible sections
 * ------------------------------------------------------------------ */

/** The heading on a collapsible section that was opened without one. */
const DEFAULT_SUMMARY = "Details";

/** What a container directive may hold, which is anything a document may. */
type DirectiveContent = BlockContent | DefinitionContent;

/**
 * The title a directive was opened with, taken off the front of its body.
 *
 * `:::details[Show the answer]` puts the label in a leading paragraph, flagged
 * as such. Without one the block still needs a heading — a collapsible section
 * with a blank summary is an unlabelled strip you have to click to identify —
 * so the caller's fallback stands in.
 */
function directiveTitle(
  children: DirectiveContent[],
  fallback: string,
): { title: Paragraph; body: DirectiveContent[] } {
  const [first] = children;
  const labelled =
    first?.type === "paragraph" &&
    (first.data as { directiveLabel?: boolean } | undefined)
      ?.directiveLabel === true;

  return labelled
    ? { title: first, body: children.slice(1) }
    : {
        title: {
          type: "paragraph",
          children: [{ type: "text", value: fallback }],
        },
        body: children,
      };
}

/**
 * `:::` blocks → the two structures a guide is allowed to build with them.
 *
 * Directives rather than raw HTML, because raw HTML never reaches the output:
 * `remark-rehype` runs without `allowDangerousHtml`, and that stays true — a
 * guide body is not an HTML injection point. `remark-directive` adds one generic
 * block syntax instead, and this plugin decides what it may mean:
 *
 *  - `:::details[Show the answer]` … `:::` → a `<details>` block, expanded from
 *    the start if it was opened `:::details[Title]{open}`;
 *  - `:::tip[Stop and smell the code]` … `:::` → a callout, in any of the kinds
 *    in `CALLOUTS`.
 *
 * Both are built *here*, before sanitisation, rather than afterwards like the
 * code blocks. The tags they need — `details`, `summary`, `div`, `p` — are ones
 * the schema already allows, and building them in mdast means the title and the
 * body are ordinary Markdown that gets sanitised along with everything else. Only
 * the decoration — classes, the chevron, the icon, the body wrapper — is added on
 * the trusted side, in `rehypeDetails` and `rehypeCallouts`.
 *
 * Everything else the syntax can match is put back as the text that was typed.
 * That is the whole reason this runs as one pass over every directive node:
 * turning the extension on also makes `:name` a directive *mid-sentence*, so a
 * guide that says `key:value` — and these guides are full of that — would
 * otherwise lose the second half of the word. Directives are a feature of this
 * one block form; anywhere else the punctuation means what it looks like.
 */
function remarkBlockDirectives() {
  return (tree: MdastRoot, file: { value: unknown }) => {
    const source = String(file.value);

    visit(tree, (node, index, parent) => {
      if (
        node.type !== "containerDirective" &&
        node.type !== "leafDirective" &&
        node.type !== "textDirective"
      ) {
        return;
      }

      const kind =
        node.type === "containerDirective" ? calloutKind(node.name) : null;

      if (
        node.type !== "containerDirective" ||
        (node.name !== "details" && kind === null)
      ) {
        const start = node.position?.start.offset;
        const end = node.position?.end.offset;
        if (!parent || index === undefined || start === undefined || end === undefined) {
          return SKIP;
        }

        parent.children[index] = {
          type: "text",
          value: source.slice(start, end),
          position: node.position,
        };
        // The node is detached; its children are not part of the document.
        return SKIP;
      }

      if (kind !== null) {
        // The heading is always present, so what survives sanitisation is a
        // shape `rehypeCallouts` can read without guessing: the first paragraph
        // in the box is its title, and everything after it is the body.
        const { title, body } = directiveTitle(node.children, CALLOUTS[kind]);

        node.children = [title, ...body];
        node.data = {
          ...node.data,
          hName: "div",
          // The kind has to reach the far side of the sanitiser to be styled,
          // and a class would not: see `SANITIZE_SCHEMA`.
          hProperties: { "data-callout": kind },
        };
        return;
      }

      const { title: summary, body } = directiveTitle(
        node.children,
        DEFAULT_SUMMARY,
      );
      summary.data = { ...summary.data, hName: "summary" };

      node.children = [summary, ...body];
      node.data = {
        ...node.data,
        hName: "details",
        hProperties: { open: node.attributes?.open !== undefined },
      };
    });
  };
}

